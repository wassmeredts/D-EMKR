-- =====================================================================
-- Nachrüstung: mehrere Flugzeuge
-- NUR ausführen, wenn du schema.sql bereits früher ausgeführt hast.
-- (Bei einer frischen Einrichtung enthält schema.sql dies schon.)
--
-- Deine bestehenden Daten bleiben erhalten: Alle Reservierungen,
-- Flüge, Mängel und Teile gehören danach zum bisherigen Flugzeug.
--
-- Supabase-Dashboard -> SQL Editor -> New query -> einfügen -> Run
-- =====================================================================

begin;

-- 1. Flugzeug-Tabelle: mehrere Einträge erlauben ---------------------
do $$
declare c record;
begin
  for c in
    select conname from pg_constraint
    where conrelid = 'public.aircraft'::regclass and contype = 'c'
  loop
    execute format('alter table public.aircraft drop constraint %I', c.conname);
  end loop;
end $$;

alter table public.aircraft alter column id drop default;
alter table public.aircraft alter column id add generated by default as identity;
select setval(
  pg_get_serial_sequence('public.aircraft', 'id'),
  coalesce((select max(id) from public.aircraft), 1)
);

alter table public.aircraft alter column registration drop default;
alter table public.aircraft alter column type set default '';
alter table public.aircraft add column if not exists created_at timestamptz not null default now();
alter table public.aircraft add constraint aircraft_registration_key unique (registration);

-- 2. Alle Daten einem Flugzeug zuordnen -------------------------------
alter table public.reservations add column aircraft_id int references public.aircraft(id) on delete cascade;
alter table public.flights      add column aircraft_id int references public.aircraft(id) on delete cascade;
alter table public.defects      add column aircraft_id int references public.aircraft(id) on delete cascade;
alter table public.parts        add column aircraft_id int references public.aircraft(id) on delete cascade;

update public.reservations set aircraft_id = (select min(id) from public.aircraft) where aircraft_id is null;
update public.flights      set aircraft_id = (select min(id) from public.aircraft) where aircraft_id is null;
update public.defects      set aircraft_id = (select min(id) from public.aircraft) where aircraft_id is null;
update public.parts        set aircraft_id = (select min(id) from public.aircraft) where aircraft_id is null;

alter table public.reservations alter column aircraft_id set not null;
alter table public.flights      alter column aircraft_id set not null;
alter table public.defects      alter column aircraft_id set not null;
alter table public.parts        alter column aircraft_id set not null;

create index reservations_aircraft_idx on public.reservations (aircraft_id, date);
create index flights_aircraft_idx on public.flights (aircraft_id, date);
create index defects_aircraft_idx on public.defects (aircraft_id, status);
create index parts_aircraft_idx on public.parts (aircraft_id);

-- 3. Überschneidungen nur noch pro Flugzeug verhindern ----------------
create or replace function public.check_reservation_overlap()
returns trigger
language plpgsql
as $$
begin
  if exists (
    select 1 from public.reservations r
    where r.aircraft_id = new.aircraft_id
      and r.date = new.date
      and r.id <> new.id
      and r.start_time < new.end_time
      and r.end_time > new.start_time
  ) then
    raise exception 'Zu diesem Zeitpunkt besteht bereits eine Reservierung.';
  end if;
  return new;
end;
$$;

-- 4. Administratoren dürfen Flugzeuge anlegen und löschen -------------
create policy "aircraft_insert" on public.aircraft
  for insert to authenticated with check (public.is_admin());
create policy "aircraft_delete" on public.aircraft
  for delete to authenticated using (public.is_admin());

commit;
